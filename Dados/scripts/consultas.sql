SELECT  *
FROM TB_ACESSOS t1
WHERE DATA_HORA = (
  SELECT MAX(DATA_HORA)
  FROM TB_ACESSOS t2
  WHERE t1.MATRICULA = t2.MATRICULA
)
AND ENTRADA_SAIDA = 1



SELECT ESTRUTURA
FROM TB_ACESSOS t1
